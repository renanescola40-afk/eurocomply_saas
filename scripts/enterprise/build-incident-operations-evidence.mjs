#!/usr/bin/env node

import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPOSITORY = 'renanescola40-afk/eurocomply_saas';
const FULL_SHA = /^[a-f0-9]{40}$/;
const REQUIRED_SEVERITIES = ['SEV-1', 'SEV-2', 'SEV-3', 'SEV-4'];
const REQUIRED_INCIDENT_ROLES = [
  'Incident commander', 'Technical lead', 'Rollback owner', 'Evidence owner',
  'Customer communication owner', 'Support owner', 'Security/privacy owner', 'Billing owner',
];
const REQUIRED_OWNERS = [
  'Incident owner', 'Technical owner', 'Security and privacy owner', 'Billing owner',
  'Rollback owner', 'Evidence owner', 'Support owner', 'Customer communication owner',
  'Observability owner', 'Database owner',
];

function digest(content) {
  return createHash('sha256').update(content).digest('hex');
}

function gitHead(root) {
  try {
    return execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim();
  } catch {
    return '';
  }
}

function hasAll(content, values) {
  return values.filter((value) => !content.includes(value));
}

function writeJson(path, document) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, `${JSON.stringify(document, null, 2)}\n`);
}

function run() {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
  const incidentPath = join(root, 'docs/operations/INCIDENT_RESPONSE_RUNBOOK.md');
  const ownershipPath = join(root, 'docs/operations/OPERATIONS_OWNERSHIP.md');
  const incident = readFileSync(incidentPath, 'utf8');
  const ownership = readFileSync(ownershipPath, 'utf8');
  const targetSha = process.env.TARGET_SHA || process.env.GITHUB_SHA || '';
  const observedSha = gitHead(root);
  const provenanceFailures = [];

  if (process.env.GITHUB_ACTIONS !== 'true') provenanceFailures.push('evidence must be generated by GitHub Actions');
  if (process.env.GITHUB_REPOSITORY !== REPOSITORY) provenanceFailures.push('repository must be canonical');
  if (!FULL_SHA.test(targetSha)) provenanceFailures.push('targetSha must be a full Git SHA');
  if (observedSha !== targetSha) provenanceFailures.push('checked-out SHA must equal targetSha');
  if (!/^\d+$/.test(process.env.GITHUB_RUN_ID || '')) provenanceFailures.push('runId must be numeric');

  const incidentFailures = [
    ...hasAll(incident, REQUIRED_SEVERITIES).map((item) => `missing severity ${item}`),
    ...hasAll(incident, REQUIRED_INCIDENT_ROLES).map((item) => `missing incident role ${item}`),
  ];
  if (!incident.includes('## First 15 minutes')) incidentFailures.push('missing first 15 minutes procedure');
  if (!incident.includes('## Scenario runbooks')) incidentFailures.push('missing scenario runbooks');
  if (!incident.includes('Release is **No-Go**')) incidentFailures.push('missing release No-Go ownership rule');

  const ownershipFailures = hasAll(ownership, REQUIRED_OWNERS).map((item) => `missing accountable role ${item}`);
  if (!ownership.includes('## Release binding requirement')) ownershipFailures.push('missing release binding requirement');
  if (!ownership.includes('## Handover and absence')) ownershipFailures.push('missing handover policy');
  if (!ownership.includes('## Risks and trade-offs')) ownershipFailures.push('missing risks and trade-offs');
  if (!ownership.includes('## Rollback')) ownershipFailures.push('missing rollback guidance');

  const generatedAt = new Date().toISOString();
  const common = {
    generatedAt,
    reviewedAt: generatedAt,
    repository: process.env.GITHUB_REPOSITORY || '',
    branch: process.env.GITHUB_HEAD_REF || process.env.GITHUB_REF_NAME || '',
    targetSha,
    observedSha,
    githubRunId: String(process.env.GITHUB_RUN_ID || ''),
    evidenceIntegrity: {
      containsSensitiveValues: false,
      rawIncidentDataStored: false,
      exactShaBound: provenanceFailures.length === 0,
      generatedByProtectedAutomation: process.env.GITHUB_ACTIONS === 'true',
    },
  };

  const incidentAllFailures = [...incidentFailures, ...provenanceFailures];
  const incidentPassed = incidentAllFailures.length === 0;
  const incidentEvidence = {
    schema: 'risck-comply.incident-response-evidence.v1',
    evidenceItem: 'incident-response-validation',
    status: incidentPassed ? 'Complete' : 'Open',
    outcome: incidentPassed ? 'passed' : 'not_verified',
    ...common,
    checks: [
      { name: 'severityModel', passed: incidentPassed },
      { name: 'requiredRoles', passed: incidentFailures.filter((x) => x.includes('role')).length === 0 },
      { name: 'first15Minutes', passed: incident.includes('## First 15 minutes') },
      { name: 'scenarioRunbooks', passed: incident.includes('## Scenario runbooks') },
      { name: 'releaseNoGoRule', passed: incident.includes('Release is **No-Go**') },
    ],
    source: { path: 'docs/operations/INCIDENT_RESPONSE_RUNBOOK.md', digest: digest(incident) },
    failures: incidentAllFailures,
  };

  const ownershipAllFailures = [...ownershipFailures, ...provenanceFailures];
  const ownershipPassed = ownershipAllFailures.length === 0;
  const ownershipEvidence = {
    schema: 'risck-comply.operations-ownership-evidence.v1',
    evidenceItem: 'operations-ownership',
    status: ownershipPassed ? 'Complete' : 'Open',
    outcome: ownershipPassed ? 'passed' : 'not_verified',
    ...common,
    checks: [
      { name: 'accountableRoles', passed: ownershipFailures.filter((x) => x.includes('role')).length === 0 },
      { name: 'releaseBinding', passed: ownership.includes('## Release binding requirement') },
      { name: 'handover', passed: ownership.includes('## Handover and absence') },
      { name: 'riskAndRollback', passed: ownership.includes('## Risks and trade-offs') && ownership.includes('## Rollback') },
    ],
    source: { path: 'docs/operations/OPERATIONS_OWNERSHIP.md', digest: digest(ownership) },
    failures: ownershipAllFailures,
  };

  writeJson(join(root, 'docs/security/evidence/release/incident-response-validation.json'), incidentEvidence);
  writeJson(join(root, 'docs/security/evidence/release/operations-ownership.json'), ownershipEvidence);

  if (!incidentPassed || !ownershipPassed) {
    for (const failure of [...incidentAllFailures, ...ownershipAllFailures]) console.error(`- ${failure}`);
    process.exit(1);
  }

  console.log('Incident severity and operations ownership evidence completed for exact SHA.');
}

run();
