#!/usr/bin/env node

import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const CANONICAL_REPOSITORY = 'renanescola40-afk/eurocomply_saas';
const FULL_SHA = /^[a-f0-9]{40}$/;
const OUTPUT = 'docs/security/evidence/runtime/auth-recovery-validation.json';
const DEFAULT_GITHUB_CHECKS = 'artifacts/enterprise-readiness/github-checks-evidence.json';
const REQUIRED_LOCALES = ['en', 'pt', 'es', 'fr', 'it', 'de'];

function digest(value) {
  return createHash('sha256').update(value).digest('hex');
}

function checkStatus(document, name) {
  return document?.checks?.find((item) => item?.name === name)?.status === 'PASS';
}

function containsEvery(source, values) {
  return values.every((value) => source.includes(value));
}

export function evaluateAccountRecoveryCoverage(sources) {
  const secureRequestRoute = containsEvery(sources.route, [
    'assertTrustedOrigin(request)',
    'readBoundedJsonRequest<unknown>',
    "policy: 'password-reset'",
    "failureMode: 'fail-closed'",
    'privacySafeRecoveryKey(email)',
    'createServerSupabaseClient()',
    'resetPasswordForEmail(email, { redirectTo })',
    "noStoreJson({ error: 'account_recovery_unavailable' }, { status: 503 })",
  ]);
  const enumerationSafe = containsEvery(sources.route, [
    'GENERIC_RECOVERY_MESSAGE',
    'If an account exists for that email, a secure recovery link will be sent.',
    "area: 'account_recovery_provider'",
  ])
    && !sources.route.includes('userExists')
    && !sources.route.includes('account_not_found')
    && !sources.route.includes('email_not_found');
  const requestUx = containsEvery(sources.requestPage, [
    "fetch('/api/auth/recovery'",
    'aria-live="polite"',
    "role={notice.tone === 'error' ? 'alert' : 'status'}",
  ])
    && REQUIRED_LOCALES.every((locale) => sources.requestPage.includes(`${locale}: {`));
  const resetCompletion = containsEvery(sources.resetPage, [
    "event === 'PASSWORD_RECOVERY'",
    'supabase.auth.updateUser({ password })',
    'minLength={8}',
    'password !== confirmation',
    'await supabase.auth.signOut()',
  ]);
  const routeExposure = sources.middleware.includes("'/reset-password'")
    && sources.middleware.includes("'/recuperar-senha'")
    && sources.authGate.includes("'reset-password'");
  const loginEntrypoint = sources.login.includes('href={`/${locale}/recuperar-senha`}')
    && sources.login.includes('Forgot your password?')
    && sources.login.includes('Esqueceu a senha?');
  const safeUnconfiguredClient = sources.browserClient.includes('updateUser: async () =>')
    && sources.browserClient.includes("error: new Error('Supabase client not configured')");
  const routeTests = containsEvery(sources.routeTest, [
    'returns the same generic no-store response',
    'blocks untrusted origins',
    'fails closed when the distributed password-reset limiter blocks',
    'uses one sanitized provider-unavailable response',
  ]);
  const browserTests = containsEvery(sources.e2eTest, [
    "test.describe('enterprise account recovery'",
    'login exposes a localized recovery entrypoint',
    'recovery request presents the same generic success message',
    'reset completion rejects a missing or expired recovery session',
  ]);

  const checks = {
    secureRequestRoute,
    enumerationSafe,
    requestUx,
    resetCompletion,
    routeExposure,
    loginEntrypoint,
    safeUnconfiguredClient,
    routeTests,
    browserTests,
  };

  return {
    checks,
    complete: Object.values(checks).every(Boolean),
  };
}

export function evaluateExactShaChecks(githubChecks, targetSha) {
  return {
    evidenceComplete: githubChecks?.status === 'Complete' && githubChecks?.outcome === 'passed',
    exactSha: githubChecks?.targetSha === targetSha,
    fullSecuritySuite: checkStatus(githubChecks, 'fullSecuritySuite'),
    requiredChecks: checkStatus(githubChecks, 'requiredChecks'),
  };
}

export function buildAccountRecoveryEvidence({
  coverage,
  exactChecks,
  repository,
  branch,
  targetSha,
  observedSha,
  runId,
  githubActions,
  sourceDigests,
  generatedAt = new Date().toISOString(),
}) {
  const failures = [];
  if (!githubActions) failures.push('evidence must be generated by GitHub Actions');
  if (repository !== CANONICAL_REPOSITORY) failures.push('repository must be canonical');
  if (!String(branch ?? '').trim()) failures.push('branch must be present');
  if (!FULL_SHA.test(targetSha)) failures.push('targetSha must be a full Git SHA');
  if (observedSha !== targetSha) failures.push('checked-out SHA must equal targetSha');
  if (!/^\d+$/.test(String(runId))) failures.push('runId must be numeric');

  const exactShaProvenance = failures.length === 0;
  const executionProven = exactChecks.evidenceComplete
    && exactChecks.exactSha
    && exactChecks.fullSecuritySuite
    && exactChecks.requiredChecks;
  const passed = coverage.complete && exactShaProvenance && executionProven;

  if (!coverage.complete) failures.push('account recovery source and test coverage is incomplete');
  if (!executionProven) failures.push('required exact-SHA execution evidence is incomplete');

  return {
    schema: 'risck-comply.auth-recovery-validation.v1',
    evidenceItem: 'auth-recovery-validation',
    status: passed ? 'Complete' : 'Open',
    outcome: passed ? 'passed' : 'not_verified',
    generatedAt,
    repository,
    branch,
    targetSha,
    observedSha,
    githubRunId: String(runId),
    summary: passed
      ? 'Account recovery request and password-reset completion controls passed on the exact assessed SHA.'
      : 'Account recovery validation is incomplete; enterprise release remains blocked for this control.',
    checks: [
      { name: 'requestRouteSecurity', passed: coverage.checks.secureRequestRoute },
      { name: 'enumerationResistance', passed: coverage.checks.enumerationSafe },
      { name: 'localizedRequestUx', passed: coverage.checks.requestUx },
      { name: 'passwordResetCompletion', passed: coverage.checks.resetCompletion },
      { name: 'publicRouteExposure', passed: coverage.checks.routeExposure },
      { name: 'loginEntrypoint', passed: coverage.checks.loginEntrypoint },
      { name: 'providerConfigurationFailureSafety', passed: coverage.checks.safeUnconfiguredClient },
      { name: 'routeTests', passed: coverage.checks.routeTests && executionProven },
      { name: 'browserTests', passed: coverage.checks.browserTests && executionProven },
    ],
    sourceCoverage: coverage.checks,
    executionEvidence: {
      exactShaChecksComplete: exactChecks.evidenceComplete,
      exactShaMatches: exactChecks.exactSha,
      fullSecuritySuitePassed: exactChecks.fullSecuritySuite,
      requiredChecksPassed: exactChecks.requiredChecks,
    },
    controlsVerified: passed ? ['Account recovery validated'] : [],
    sourceDigests,
    failures,
    evidenceLocations: [
      'src/app/api/auth/recovery/route.ts',
      'src/app/[locale]/recuperar-senha/page.tsx',
      'src/app/[locale]/reset-password/page.tsx',
      'src/app/[locale]/login/page.tsx',
      'tests/e2e/account-recovery.spec.ts',
      'src/app/api/auth/recovery/route.test.ts',
      DEFAULT_GITHUB_CHECKS,
    ],
    evidenceBoundary: 'This exact-SHA evidence validates repository behavior, route security, enumeration-safe responses, localized UX, password-reset completion logic, and execution in required CI. It does not prove production email delivery, Supabase provider availability, inbox receipt, token delivery latency, or a real production account recovery transaction.',
    evidenceIntegrity: {
      containsSensitiveValues: false,
      emailAddressesStored: false,
      recoveryTokensStored: false,
      passwordsStored: false,
      providerPayloadsStored: false,
      browserStorageStored: false,
      exactShaBound: exactShaProvenance && exactChecks.exactSha,
    },
  };
}

function head(root) {
  try {
    return execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim();
  } catch {
    return '';
  }
}

function run() {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
  const paths = {
    route: 'src/app/api/auth/recovery/route.ts',
    requestPage: 'src/app/[locale]/recuperar-senha/page.tsx',
    resetPage: 'src/app/[locale]/reset-password/page.tsx',
    login: 'src/app/[locale]/login/page.tsx',
    middleware: 'src/middleware.ts',
    authGate: 'src/components/auth/AuthProviderGate.tsx',
    browserClient: 'src/integrations/supabase/client.ts',
    routeTest: 'src/app/api/auth/recovery/route.test.ts',
    e2eTest: 'tests/e2e/account-recovery.spec.ts',
  };
  const sources = Object.fromEntries(
    Object.entries(paths).map(([key, relativePath]) => [key, readFileSync(join(root, relativePath), 'utf8')]),
  );
  const githubChecksPath = process.env.GITHUB_CHECKS_EVIDENCE_PATH || DEFAULT_GITHUB_CHECKS;
  const githubChecksRaw = readFileSync(join(root, githubChecksPath), 'utf8');
  const githubChecks = JSON.parse(githubChecksRaw);
  const targetSha = process.env.TARGET_SHA || process.env.GITHUB_SHA || '';
  const coverage = evaluateAccountRecoveryCoverage(sources);
  const exactChecks = evaluateExactShaChecks(githubChecks, targetSha);
  const evidence = buildAccountRecoveryEvidence({
    coverage,
    exactChecks,
    repository: process.env.GITHUB_REPOSITORY ?? '',
    branch: process.env.GITHUB_HEAD_REF || process.env.GITHUB_REF_NAME || '',
    targetSha,
    observedSha: head(root),
    runId: process.env.GITHUB_RUN_ID ?? '',
    githubActions: process.env.GITHUB_ACTIONS === 'true',
    sourceDigests: Object.fromEntries(
      Object.entries(sources).map(([key, source]) => [key, digest(source)]),
    ),
  });

  const output = join(root, OUTPUT);
  mkdirSync(dirname(output), { recursive: true });
  writeFileSync(output, `${JSON.stringify(evidence, null, 2)}\n`);

  if (evidence.status !== 'Complete') process.exit(1);
}

if (process.argv[1] && fileURLToPath(new URL(`file://${process.argv[1]}`)) === fileURLToPath(import.meta.url)) run();
