#!/usr/bin/env node

import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const CANONICAL_REPOSITORY = 'renanescola40-afk/eurocomply_saas';
const FULL_SHA = /^[a-f0-9]{40}$/;
const OUTPUT = 'docs/security/evidence/p1/centralized-logging-alerts.json';

function digest(value) {
  return createHash('sha256').update(value).digest('hex');
}

function includesAll(value, needles) {
  return needles.every((needle) => value.includes(needle));
}

export function evaluateLoggingAlerting({ loggerSource, alertingRunbook, loggingRunbook }) {
  const checks = {
    structuredJsonLogs: includesAll(loggerSource, ['JSON.stringify', 'timestamp:', 'requestId:', 'event:']),
    sensitiveDataRedaction: includesAll(loggerSource, ['SENSITIVE_KEY_PATTERN', 'SENSITIVE_VALUE_PATTERNS', 'REDACTED_VALUE']),
    standardizedSecurityEvents: includesAll(loggerSource, ['STANDARD_SECURITY_EVENTS', 'rls_validation_failed', 'audit_chain_invalid', 'webhook_failed']),
    sentryAlertRouting: includesAll(loggerSource, ['Sentry.withScope', 'captureMessage', 'alert_severity', 'security_event']),
    severityThresholdsDocumented: includesAll(alertingRunbook, ['SEV-1', 'SEV-2', 'Threshold', 'Customer communication']),
    ownerRoutingDocumented: includesAll(alertingRunbook, ['Primary owner', 'Backup owner', 'Release is **No-Go**']),
    productionLogDestinationsDocumented: includesAll(loggingRunbook, ['Vercel', 'Supabase logs', 'Sentry']),
    evidenceCaptureDocumented: includesAll(alertingRunbook, ['Evidence to capture', 'Deployment SHA', 'Closure criteria']),
  };

  return {
    checks,
    centralizedLogging: checks.structuredJsonLogs
      && checks.sensitiveDataRedaction
      && checks.standardizedSecurityEvents
      && checks.productionLogDestinationsDocumented,
    alertRouting: checks.sentryAlertRouting
      && checks.severityThresholdsDocumented
      && checks.ownerRoutingDocumented
      && checks.evidenceCaptureDocumented,
  };
}

export function buildEvidence({ evaluation, repository, branch, targetSha, observedSha, runId, githubActions, generatedAt = new Date().toISOString(), sourceDigests }) {
  const provenanceFailures = [];
  if (!githubActions) provenanceFailures.push('evidence must be generated by GitHub Actions');
  if (repository !== CANONICAL_REPOSITORY) provenanceFailures.push('repository must be canonical');
  if (!String(branch ?? '').trim()) provenanceFailures.push('branch must be present');
  if (!FULL_SHA.test(targetSha)) provenanceFailures.push('targetSha must be a full Git SHA');
  if (observedSha !== targetSha) provenanceFailures.push('checked-out SHA must equal targetSha');
  if (!/^\d+$/.test(String(runId))) provenanceFailures.push('runId must be numeric');

  const exactShaProvenance = provenanceFailures.length === 0;
  const passed = evaluation.centralizedLogging && evaluation.alertRouting && exactShaProvenance;

  return {
    schema: 'risck-comply.centralized-logging-alert-evidence.v1',
    evidenceItem: 'centralized-logging-alerts',
    status: passed ? 'Complete' : 'Open',
    outcome: passed ? 'passed' : 'not_verified',
    generatedAt,
    repository,
    branch,
    targetSha,
    observedSha,
    githubRunId: String(runId),
    checks: [
      { name: 'centralizedLogging', passed: evaluation.centralizedLogging && exactShaProvenance },
      { name: 'alertRouting', passed: evaluation.alertRouting && exactShaProvenance },
      { name: 'exactShaProvenance', passed: exactShaProvenance },
    ],
    checkResults: {
      ...evaluation.checks,
      centralizedLogging: evaluation.centralizedLogging,
      alertRouting: evaluation.alertRouting,
      exactShaProvenance,
    },
    controlsVerified: passed ? ['Centralized logging validated', 'Alert routing validated'] : [],
    failures: provenanceFailures,
    sourceDigests,
    evidenceLocations: [
      'src/server/observability/logger.ts',
      'docs/operations/ALERTING.md',
      'docs/security/LOGGING_AUDIT_MONITORING.md',
    ],
    evidenceBoundary: 'Validates repository logging, redaction, security-event routing, alert severity, ownership and evidence-capture contracts for the exact SHA. It does not prove live provider ingestion, paging delivery or incident response execution.',
    evidenceIntegrity: {
      containsSensitiveValues: false,
      rawLogsStored: false,
      providerPayloadsStored: false,
      exactShaBound: passed,
    },
  };
}

function head(root) {
  try {
    return execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim();
  } catch {
    return '';
  }
}

function run() {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
  const loggerSource = readFileSync(join(root, 'src/server/observability/logger.ts'), 'utf8');
  const alertingRunbook = readFileSync(join(root, 'docs/operations/ALERTING.md'), 'utf8');
  const loggingRunbook = readFileSync(join(root, 'docs/security/LOGGING_AUDIT_MONITORING.md'), 'utf8');
  const evaluation = evaluateLoggingAlerting({ loggerSource, alertingRunbook, loggingRunbook });
  const evidence = buildEvidence({
    evaluation,
    repository: process.env.GITHUB_REPOSITORY ?? '',
    branch: process.env.GITHUB_HEAD_REF || process.env.GITHUB_REF_NAME || '',
    targetSha: process.env.TARGET_SHA || process.env.GITHUB_SHA || '',
    observedSha: head(root),
    runId: process.env.GITHUB_RUN_ID ?? '',
    githubActions: process.env.GITHUB_ACTIONS === 'true',
    sourceDigests: {
      logger: digest(loggerSource),
      alertingRunbook: digest(alertingRunbook),
      loggingRunbook: digest(loggingRunbook),
    },
  });

  const output = join(root, OUTPUT);
  mkdirSync(dirname(output), { recursive: true });
  writeFileSync(output, `${JSON.stringify(evidence, null, 2)}\n`);
  if (evidence.status !== 'Complete') process.exit(1);
}

if (process.argv[1] && fileURLToPath(new URL(`file://${process.argv[1]}`)) === fileURLToPath(import.meta.url)) run();
