#!/usr/bin/env node

import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const CANONICAL_REPOSITORY = 'renanescola40-afk/eurocomply_saas';
const FULL_SHA = /^[a-f0-9]{40}$/;
const ACCESSIBILITY_OUTPUT = 'docs/security/evidence/runtime/accessibility-validation.json';
const ANALYTICS_OUTPUT = 'docs/security/evidence/runtime/analytics-consent-validation.json';
const DEFAULT_GITHUB_CHECKS = 'artifacts/enterprise-readiness/github-checks-evidence.json';

function digest(value) {
  return createHash('sha256').update(value).digest('hex');
}

function checkStatus(document, name) {
  const check = document?.checks?.find((item) => item?.name === name);
  return check?.status === 'PASS';
}

export function evaluateAccessibilityConsentCoverage({ specSource, bannerSource, analyticsSource, workflowSource }) {
  const checks = {
    dedicatedSuite: specSource.includes("test.describe('enterprise accessibility and analytics consent acceptance'"),
    keyboardNavigation: specSource.includes('keyboard-only navigation reaches critical controls')
      && specSource.includes("page.keyboard.press('Tab')")
      && specSource.includes('toBeFocused()'),
    screenReaderSemantics: specSource.includes('semantic landmarks and accessible names support screen readers')
      && specSource.includes('invalidAriaReferences')
      && specSource.includes('unnamedInteractive')
      && specSource.includes('unlabeledControls')
      && specSource.includes('imagesMissingAlt'),
    consentDialogSemantics: bannerSource.includes('role="dialog"')
      && bannerSource.includes('aria-labelledby={CONSENT_TITLE_ID}')
      && bannerSource.includes('aria-describedby={CONSENT_DESCRIPTION_ID}')
      && bannerSource.includes('dialogRef.current?.focus()'),
    preConsentBlocking: specSource.includes('analytics stays blocked before consent and decline persists')
      && specSource.includes('toHaveCount(0)')
      && analyticsSource.includes('!hasAnalyticsConsent()'),
    explicitGrantRequired: specSource.includes('analytics loads only after explicit consent')
      && specSource.includes("toBe('granted')")
      && specSource.includes('analyticsRequests'),
    denialStopsRecording: analyticsSource.includes('window.posthog?.stopSessionRecording?.()')
      && analyticsSource.includes('window.posthog?.opt_out_capturing?.()'),
    replayConsentGuard: analyticsSource.includes('export function updateSessionRecordingForPath')
      && analyticsSource.includes('if (!hasAnalyticsConsent())'),
    protectedRuntimeConfiguration: workflowSource.includes("NEXT_PUBLIC_ANALYTICS_REQUIRE_CONSENT: 'true'")
      && workflowSource.includes('NEXT_PUBLIC_POSTHOG_KEY: phc_ci_synthetic_public_key')
      && workflowSource.includes('NEXT_PUBLIC_POSTHOG_HOST: https://analytics-ci.invalid'),
  };

  return {
    checks,
    keyboardCoverage: checks.dedicatedSuite && checks.keyboardNavigation,
    screenReaderCoverage: checks.dedicatedSuite && checks.screenReaderSemantics && checks.consentDialogSemantics,
    analyticsConsentCoverage: checks.dedicatedSuite
      && checks.preConsentBlocking
      && checks.explicitGrantRequired
      && checks.denialStopsRecording
      && checks.replayConsentGuard
      && checks.protectedRuntimeConfiguration,
  };
}

export function evaluateExactShaChecks(githubChecks, targetSha) {
  return {
    evidenceComplete: githubChecks?.status === 'Complete' && githubChecks?.outcome === 'passed',
    exactSha: githubChecks?.targetSha === targetSha,
    fullSecuritySuite: checkStatus(githubChecks, 'fullSecuritySuite'),
    requiredChecks: checkStatus(githubChecks, 'requiredChecks'),
  };
}

export function buildAccessibilityConsentEvidence({
  coverage,
  exactChecks,
  repository,
  branch,
  targetSha,
  observedSha,
  runId,
  githubActions,
  generatedAt = new Date().toISOString(),
  sourceDigests,
}) {
  const provenanceFailures = [];
  if (!githubActions) provenanceFailures.push('evidence must be generated by GitHub Actions');
  if (repository !== CANONICAL_REPOSITORY) provenanceFailures.push('repository must be canonical');
  if (!String(branch ?? '').trim()) provenanceFailures.push('branch must be present');
  if (!FULL_SHA.test(targetSha)) provenanceFailures.push('targetSha must be a full Git SHA');
  if (observedSha !== targetSha) provenanceFailures.push('checked-out SHA must equal targetSha');
  if (!/^\d+$/.test(String(runId))) provenanceFailures.push('runId must be numeric');

  const exactShaProvenance = provenanceFailures.length === 0;
  const executionProven = exactChecks.evidenceComplete
    && exactChecks.exactSha
    && exactChecks.fullSecuritySuite
    && exactChecks.requiredChecks;
  const keyboardPassed = coverage.keyboardCoverage && executionProven && exactShaProvenance;
  const screenReaderPassed = coverage.screenReaderCoverage && executionProven && exactShaProvenance;
  const analyticsPassed = coverage.analyticsConsentCoverage && executionProven && exactShaProvenance;
  const accessibilityPassed = keyboardPassed && screenReaderPassed;

  const common = {
    generatedAt,
    repository,
    branch,
    targetSha,
    observedSha,
    githubRunId: String(runId),
    sourceDigests,
    executionEvidence: {
      exactShaChecksComplete: exactChecks.evidenceComplete,
      exactShaMatches: exactChecks.exactSha,
      fullSecuritySuitePassed: exactChecks.fullSecuritySuite,
      requiredChecksPassed: exactChecks.requiredChecks,
    },
    failures: provenanceFailures,
    evidenceIntegrity: {
      containsSensitiveValues: false,
      rawBrowserTracesStored: false,
      screenshotsStoredInEvidence: false,
      analyticsPayloadsStored: false,
      customerDataStored: false,
      exactShaBound: exactShaProvenance && exactChecks.exactSha,
    },
  };

  return {
    accessibility: {
      schema: 'risck-comply.accessibility-validation.v1',
      evidenceItem: 'accessibility-validation',
      status: accessibilityPassed ? 'Complete' : 'Open',
      outcome: accessibilityPassed ? 'passed' : 'not_verified',
      ...common,
      checks: [
        { name: 'keyboard', passed: keyboardPassed },
        { name: 'screenReader', passed: screenReaderPassed },
      ],
      checkResults: {
        ...coverage.checks,
        exactShaProvenance,
        executionProven,
      },
      controlsVerified: accessibilityPassed
        ? ['Keyboard accessibility validated', 'Screen-reader accessibility validated']
        : [],
      evidenceLocations: [
        'tests/e2e/enterprise-accessibility-consent.spec.ts',
        'src/components/analytics/AnalyticsConsentBanner.tsx',
        DEFAULT_GITHUB_CHECKS,
      ],
      evidenceBoundary: 'Validates keyboard reachability, focus behavior, semantic landmarks, programmatic labels, accessible names, ARIA references and image alternatives in Chromium for the exact SHA. It does not certify every assistive technology, WCAG conformance level or authenticated product surface.',
    },
    analytics: {
      schema: 'risck-comply.analytics-consent-validation.v1',
      evidenceItem: 'analytics-consent-validation',
      status: analyticsPassed ? 'Complete' : 'Open',
      outcome: analyticsPassed ? 'passed' : 'not_verified',
      ...common,
      checks: [
        { name: 'analyticsConsent', passed: analyticsPassed },
      ],
      checkResults: {
        preConsentBlocking: coverage.checks.preConsentBlocking,
        explicitGrantRequired: coverage.checks.explicitGrantRequired,
        denialStopsRecording: coverage.checks.denialStopsRecording,
        replayConsentGuard: coverage.checks.replayConsentGuard,
        protectedRuntimeConfiguration: coverage.checks.protectedRuntimeConfiguration,
        exactShaProvenance,
        executionProven,
      },
      controlsVerified: analyticsPassed ? ['Analytics consent validated'] : [],
      evidenceLocations: [
        'tests/e2e/enterprise-accessibility-consent.spec.ts',
        'src/components/analytics/AnalyticsConsentBanner.tsx',
        'src/lib/analytics/posthog-client.ts',
        '.github/workflows/full-security-suite.yml',
        DEFAULT_GITHUB_CHECKS,
      ],
      evidenceBoundary: 'Validates that the PostHog script is absent before consent, denial persists without loading analytics, explicit grant enables the synthetic provider script, and session recording remains consent-gated on the exact SHA. It does not prove production PostHog ingestion, legal advice or consent-copy approval.',
    },
  };
}

function head(root) {
  try {
    return execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim();
  } catch {
    return '';
  }
}

function run() {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
  const specSource = readFileSync(join(root, 'tests/e2e/enterprise-accessibility-consent.spec.ts'), 'utf8');
  const bannerSource = readFileSync(join(root, 'src/components/analytics/AnalyticsConsentBanner.tsx'), 'utf8');
  const analyticsSource = readFileSync(join(root, 'src/lib/analytics/posthog-client.ts'), 'utf8');
  const workflowSource = readFileSync(join(root, '.github/workflows/full-security-suite.yml'), 'utf8');
  const githubChecksPath = process.env.GITHUB_CHECKS_EVIDENCE_PATH || DEFAULT_GITHUB_CHECKS;
  const githubChecksRaw = readFileSync(join(root, githubChecksPath), 'utf8');
  const githubChecks = JSON.parse(githubChecksRaw);
  const targetSha = process.env.TARGET_SHA || process.env.GITHUB_SHA || '';
  const coverage = evaluateAccessibilityConsentCoverage({ specSource, bannerSource, analyticsSource, workflowSource });
  const exactChecks = evaluateExactShaChecks(githubChecks, targetSha);
  const evidence = buildAccessibilityConsentEvidence({
    coverage,
    exactChecks,
    repository: process.env.GITHUB_REPOSITORY ?? '',
    branch: process.env.GITHUB_HEAD_REF || process.env.GITHUB_REF_NAME || '',
    targetSha,
    observedSha: head(root),
    runId: process.env.GITHUB_RUN_ID ?? '',
    githubActions: process.env.GITHUB_ACTIONS === 'true',
    sourceDigests: {
      acceptanceSpec: digest(specSource),
      consentBanner: digest(bannerSource),
      analyticsClient: digest(analyticsSource),
      fullSecurityWorkflow: digest(workflowSource),
      githubChecks: digest(githubChecksRaw),
    },
  });

  for (const [relativePath, document] of [
    [ACCESSIBILITY_OUTPUT, evidence.accessibility],
    [ANALYTICS_OUTPUT, evidence.analytics],
  ]) {
    const output = join(root, relativePath);
    mkdirSync(dirname(output), { recursive: true });
    writeFileSync(output, `${JSON.stringify(document, null, 2)}\n`);
  }

  if (evidence.accessibility.status !== 'Complete' || evidence.analytics.status !== 'Complete') process.exit(1);
}

if (process.argv[1] && fileURLToPath(new URL(`file://${process.argv[1]}`)) === fileURLToPath(import.meta.url)) run();
