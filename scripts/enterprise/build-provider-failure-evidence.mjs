#!/usr/bin/env node

import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const CANONICAL_REPOSITORY = 'renanescola40-afk/eurocomply_saas';
const FULL_SHA = /^[a-f0-9]{40}$/;
const OUTPUT = 'docs/security/evidence/runtime/provider-failure-classification.json';
const DEFAULT_GITHUB_CHECKS = 'artifacts/enterprise-readiness/github-checks-evidence.json';
const REQUIRED_KINDS = [
  'configuration',
  'authentication',
  'authorization',
  'rate_limited',
  'timeout',
  'unavailable',
  'invalid_request',
  'conflict',
  'rejected',
  'unknown',
];

function digest(value) {
  return createHash('sha256').update(value).digest('hex');
}

function containsEvery(source, values) {
  return values.every((value) => source.includes(value));
}

function checkStatus(document, name) {
  return document?.checks?.find((item) => item?.name === name)?.status === 'PASS';
}

export function evaluateProviderFailureCoverage(sources) {
  const taxonomy = REQUIRED_KINDS.every((kind) => sources.taxonomy.includes(`'${kind}'`))
    && containsEvery(sources.taxonomy, [
      'export class ProviderFailureError',
      'classifyProviderFailure',
      'providerConfigurationFailure',
      'toSafeSummary()',
      'publicCode',
      'retryable',
      'httpStatus',
    ]);
  const safeApiContract = containsEvery(sources.apiGuards, [
    'if (isProviderFailureError(error))',
    "area: 'provider_failure'",
    'error: error.publicCode',
    'retryable: error.retryable',
    '{ status: error.httpStatus }',
    'return noStoreJson(',
  ])
    && !sources.apiGuards.includes('error.providerCode, requestId')
    && !sources.apiGuards.includes('error.message, requestId');
  const stripeIntegration = containsEvery(sources.checkout, [
    "classifyProviderFailure('stripe', 'customer_update'",
    "classifyProviderFailure('stripe', 'customer_create'",
    "classifyProviderFailure('stripe', 'checkout_session_create'",
    "classifyProviderFailure('stripe', 'checkout_session_expire'",
  ]) && containsEvery(sources.portal, [
    "classifyProviderFailure('stripe', 'billing_portal_session_create'",
    "classifyProviderFailure('supabase', 'billing_profile_lookup'",
  ]);
  const emailIntegration = containsEvery(sources.email, [
    "providerConfigurationFailure('resend', 'send_email'",
    "classifyProviderFailure('resend', 'send_email'",
    'if (!providerFailure.retryable || attempt >= attemptsToRun) break;',
    'failure: configurationFailure.toSafeSummary()',
    'error: `${providerFailure.kind}:${providerFailure.providerCode}`',
  ]) && !sources.email.includes('data.error?.message ?');
  const recoveryIntegration = containsEvery(sources.recovery, [
    "classifyProviderFailure('supabase', 'password_recovery_request'",
    'providerFailureContext(providerFailure)',
    "noStoreJson({ error: 'account_recovery_unavailable' }, { status: 503 })",
  ]);
  const tests = containsEvery(sources.taxonomyTest, [
    "describe('provider failure classification'",
    'distinguishes rate limits, timeouts, authentication, authorization and unavailability',
    'never copies raw provider messages, credentials or payloads into safe summaries',
    'uses one central no-store API response contract for provider failures',
    'integrates the taxonomy into real Stripe, Resend and Supabase boundaries',
  ]) && containsEvery(sources.recoveryTest, [
    'recording a distinguishable unavailable provider failure',
    'providerFailureKind: \'unavailable\'',
    'providerFailureKind: \'configuration\'',
  ]);

  const checks = {
    centralTaxonomy: taxonomy,
    safeApiContract,
    stripeIntegration,
    resendIntegration: emailIntegration,
    supabaseIntegration: recoveryIntegration,
    classificationTests: tests,
  };
  return { checks, complete: Object.values(checks).every(Boolean) };
}

export function evaluateExactShaChecks(githubChecks, targetSha) {
  return {
    evidenceComplete: githubChecks?.status === 'Complete' && githubChecks?.outcome === 'passed',
    exactSha: githubChecks?.targetSha === targetSha,
    fullSecuritySuite: checkStatus(githubChecks, 'fullSecuritySuite'),
    requiredChecks: checkStatus(githubChecks, 'requiredChecks'),
  };
}

export function buildProviderFailureEvidence({
  coverage,
  exactChecks,
  repository,
  branch,
  targetSha,
  observedSha,
  runId,
  githubActions,
  sourceDigests,
  generatedAt = new Date().toISOString(),
}) {
  const failures = [];
  if (!githubActions) failures.push('evidence must be generated by GitHub Actions');
  if (repository !== CANONICAL_REPOSITORY) failures.push('repository must be canonical');
  if (!String(branch ?? '').trim()) failures.push('branch must be present');
  if (!FULL_SHA.test(targetSha)) failures.push('targetSha must be a full Git SHA');
  if (observedSha !== targetSha) failures.push('checked-out SHA must equal targetSha');
  if (!/^\d+$/.test(String(runId))) failures.push('runId must be numeric');

  const provenance = failures.length === 0;
  const executionProven = exactChecks.evidenceComplete
    && exactChecks.exactSha
    && exactChecks.fullSecuritySuite
    && exactChecks.requiredChecks;
  const passed = coverage.complete && provenance && executionProven;

  if (!coverage.complete) failures.push('provider failure source and test coverage is incomplete');
  if (!executionProven) failures.push('required exact-SHA execution evidence is incomplete');

  return {
    schema: 'risck-comply.provider-failure-classification.v1',
    evidenceItem: 'provider-failure-classification',
    status: passed ? 'Complete' : 'Open',
    outcome: passed ? 'passed' : 'not_verified',
    generatedAt,
    repository,
    branch,
    targetSha,
    observedSha,
    githubRunId: String(runId),
    summary: passed
      ? 'Provider failures are classified into stable operational categories on the exact assessed SHA.'
      : 'Provider failure classification is incomplete and remains unverified.',
    checks: Object.entries(coverage.checks).map(([name, value]) => ({
      name,
      passed: value && (name !== 'classificationTests' || executionProven),
    })),
    sourceCoverage: coverage.checks,
    executionEvidence: {
      exactShaChecksComplete: exactChecks.evidenceComplete,
      exactShaMatches: exactChecks.exactSha,
      fullSecuritySuitePassed: exactChecks.fullSecuritySuite,
      requiredChecksPassed: exactChecks.requiredChecks,
    },
    controlsVerified: passed ? ['Provider failures are distinguishable'] : [],
    sourceDigests,
    failures,
    evidenceLocations: [
      'src/server/providers/failure.ts',
      'src/server/security/api-guards.ts',
      'src/app/api/billing/checkout/route.ts',
      'src/app/api/billing/portal/route.ts',
      'src/lib/email/server-sender.ts',
      'src/app/api/auth/recovery/route.ts',
      'tests/security/provider-failure-classification.test.ts',
      'src/app/api/auth/recovery/route.test.ts',
      DEFAULT_GITHUB_CHECKS,
    ],
    evidenceBoundary: 'This exact-SHA evidence validates stable provider failure categories, retryability semantics, sanitized API responses, safe observability context, and integration at selected Stripe, Resend and Supabase boundaries. It does not prove a real production provider outage occurred, provider availability, alert delivery, continuity, SLA compliance, or complete classification of every future provider SDK error.',
    evidenceIntegrity: {
      containsSensitiveValues: false,
      rawProviderMessagesStored: false,
      rawProviderPayloadsStored: false,
      credentialsStored: false,
      customerDataStored: false,
      exactShaBound: provenance && exactChecks.exactSha,
    },
  };
}

function head(root) {
  try {
    return execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim();
  } catch {
    return '';
  }
}

function run() {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
  const paths = {
    taxonomy: 'src/server/providers/failure.ts',
    apiGuards: 'src/server/security/api-guards.ts',
    checkout: 'src/app/api/billing/checkout/route.ts',
    portal: 'src/app/api/billing/portal/route.ts',
    email: 'src/lib/email/server-sender.ts',
    recovery: 'src/app/api/auth/recovery/route.ts',
    taxonomyTest: 'tests/security/provider-failure-classification.test.ts',
    recoveryTest: 'src/app/api/auth/recovery/route.test.ts',
  };
  const sources = Object.fromEntries(
    Object.entries(paths).map(([key, relativePath]) => [key, readFileSync(join(root, relativePath), 'utf8')]),
  );
  const githubChecksPath = process.env.GITHUB_CHECKS_EVIDENCE_PATH || DEFAULT_GITHUB_CHECKS;
  const githubChecks = JSON.parse(readFileSync(join(root, githubChecksPath), 'utf8'));
  const targetSha = process.env.TARGET_SHA || process.env.GITHUB_SHA || '';
  const coverage = evaluateProviderFailureCoverage(sources);
  const exactChecks = evaluateExactShaChecks(githubChecks, targetSha);
  const evidence = buildProviderFailureEvidence({
    coverage,
    exactChecks,
    repository: process.env.GITHUB_REPOSITORY ?? '',
    branch: process.env.GITHUB_HEAD_REF || process.env.GITHUB_REF_NAME || '',
    targetSha,
    observedSha: head(root),
    runId: process.env.GITHUB_RUN_ID ?? '',
    githubActions: process.env.GITHUB_ACTIONS === 'true',
    sourceDigests: Object.fromEntries(
      Object.entries(sources).map(([key, source]) => [key, digest(source)]),
    ),
  });

  const output = join(root, OUTPUT);
  mkdirSync(dirname(output), { recursive: true });
  writeFileSync(output, `${JSON.stringify(evidence, null, 2)}\n`);
  if (evidence.status !== 'Complete') process.exit(1);
}

if (process.argv[1] && fileURLToPath(new URL(`file://${process.argv[1]}`)) === fileURLToPath(import.meta.url)) run();
