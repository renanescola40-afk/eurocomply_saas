#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';

const evidencePath = path.join('docs', 'security', 'evidence', 'runtime', 'supabase-live-rls-validation.json');
const registerPath = path.join('docs', 'security', 'P0_RUNTIME_EVIDENCE_REGISTER.md');
const requiredTables = [
  'organizations',
  'organization_members',
  'documents',
  'audit_events',
  'risks',
  'vendors',
  'compliance_tasks',
  'subscriptions',
  'notifications',
];
const requiredOperations = [
  'cross_tenant_read',
  'cross_tenant_insert',
  'cross_tenant_update',
  'cross_tenant_delete',
  'same_tenant_read',
];
const failures = [];

function fail(message) {
  failures.push(message);
}

function readJson(file) {
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch (error) {
    fail(`${file} is missing or invalid JSON: ${error instanceof Error ? error.message : error}`);
    return null;
  }
}

function registerMarksComplete() {
  if (!fs.existsSync(registerPath)) {
    fail(`${registerPath} is missing`);
    return false;
  }

  const register = fs.readFileSync(registerPath, 'utf8');
  const row = register
    .split('\n')
    .find((line) => line.startsWith('| Supabase live RLS validation completed |'));

  if (!row) {
    fail(`${registerPath} missing Supabase live RLS row`);
    return false;
  }

  return row.includes('| Complete |');
}

function validateGithubActionsProvenance(evidence) {
  const provenance = evidence.githubActions;
  if (!provenance || typeof provenance !== 'object' || Array.isArray(provenance)) {
    fail(`${evidencePath} missing githubActions provenance`);
    return;
  }

  if (provenance.generatedInGitHubActions !== true) {
    fail(`${evidencePath} must be stamped from GitHub Actions`);
  }

  for (const field of ['workflow', 'runId', 'runUrl', 'repository', 'commitSha', 'refName', 'actor', 'eventName', 'stampedAt']) {
    if (!provenance[field] || typeof provenance[field] !== 'string') {
      fail(`${evidencePath} githubActions.${field} is missing`);
    }
  }

  if (typeof provenance.runUrl === 'string' && !/\/actions\/runs\/[0-9]+$/.test(provenance.runUrl)) {
    fail(`${evidencePath} githubActions.runUrl must point to a GitHub Actions run`);
  }
}

const evidence = readJson(evidencePath);
const registerComplete = registerMarksComplete();

if (evidence) {
  if (evidence.status !== 'Complete') fail(`${evidencePath} status must be Complete for public production`);
  if (evidence.outcome !== 'passed') fail(`${evidencePath} outcome must be passed for public production`);
  if (evidence.runner !== 'scripts/security/run-supabase-live-tenant-isolation.mjs') {
    fail(`${evidencePath} must be generated by the strict tenant isolation validator`);
  }
  if (!String(evidence.productionGate ?? '').toLowerCase().includes('production')) {
    fail(`${evidencePath} must include a production gate statement`);
  }
  validateGithubActionsProvenance(evidence);

  const testCases = Array.isArray(evidence.testCases) ? evidence.testCases : [];
  const failedTests = testCases.filter((test) => test?.passed !== true);
  if (failedTests.length > 0) fail(`${evidencePath} contains failing test cases`);

  const tables = new Set(testCases.map((test) => test?.table).filter(Boolean));
  const operations = new Set(testCases.map((test) => test?.operation).filter(Boolean));
  for (const table of requiredTables) {
    if (!tables.has(table)) fail(`${evidencePath} missing required table coverage: ${table}`);
  }
  for (const operation of requiredOperations) {
    if (!operations.has(operation)) fail(`${evidencePath} missing required operation coverage: ${operation}`);
  }
}

if (!registerComplete) {
  fail(`${registerPath} must mark Supabase live RLS validation as Complete for public production`);
}

if (failures.length > 0) {
  console.error('Supabase live RLS production gate failed:');
  for (const failure of failures) console.error(`- ${failure}`);
  console.error('Public production remains blocked until scripts/security/run-supabase-live-tenant-isolation.mjs --update-register passes against the target Supabase project and is stamped with GitHub Actions provenance.');
  process.exit(1);
}

console.log('Supabase live RLS production gate passed.');
