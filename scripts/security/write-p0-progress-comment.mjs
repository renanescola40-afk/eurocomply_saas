import { readFileSync, writeFileSync } from 'node:fs';

const reportPath = 'p0-enterprise-progress.json';
const outputPath = 'p0-progress-comment.md';
const report = JSON.parse(readFileSync(reportPath, 'utf8'));

function renderCheck(check) {
  return `- ${check.done ? '[x]' : '[ ]'} ${check.label} (${check.id})`;
}

const lines = [
  '## P0 enterprise progress update',
  '',
  `Generated at: ${report.generatedAt}`,
  '',
  `- Combined: ${report.combined.completed}/${report.combined.total} = ${report.combined.percent}% complete, ${report.combined.remainingPercent}% remaining`,
  `- Repo readiness: ${report.repoReadiness.completed}/${report.repoReadiness.total} = ${report.repoReadiness.percent}% complete, ${report.repoReadiness.remainingPercent}% remaining`,
  `- Runtime evidence: ${report.runtimeEvidence.completed}/${report.runtimeEvidence.total} = ${report.runtimeEvidence.percent}% complete, ${report.runtimeEvidence.remainingPercent}% remaining`,
  '',
  '### Repo readiness checks',
  '',
  ...report.repoReadiness.checks.map(renderCheck),
  '',
  '### Runtime evidence checks',
  '',
  ...report.runtimeEvidence.checks.map(renderCheck),
  '',
  '_Generated by `scripts/security/write-p0-progress-comment.mjs`._',
  '',
];

writeFileSync(outputPath, `${lines.join('\n')}\n`);
console.log(`Wrote ${outputPath}`);
