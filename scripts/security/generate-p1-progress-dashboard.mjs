#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';

const indexPath = process.argv[2] || path.join('docs', 'security', 'evidence', 'p1', 'P1_EVIDENCE_INDEX.json');
const outputPath = process.argv[3] || path.join('docs', 'security', 'evidence', 'p1', 'P1_PROGRESS.md');

function fail(message) {
  console.error(`[p1-progress] ${message}`);
  process.exit(1);
}

if (!fs.existsSync(indexPath)) {
  fail(`index not found: ${indexPath}`);
}

const index = JSON.parse(fs.readFileSync(indexPath, 'utf8'));
if (!Array.isArray(index.controls)) {
  fail('index.controls must be an array');
}

const total = index.controls.length;
const complete = index.controls.filter((control) => control.status === 'Complete').length;
const exceptions = index.controls.filter((control) => control.status === 'Exception').length;
const open = index.controls.filter((control) => control.status === 'Open').length;
const percent = total === 0 ? 0 : Math.round((complete / total) * 100);

const lines = [
  '# P1 Evidence Progress',
  '',
  'This dashboard is generated from `docs/security/evidence/p1/P1_EVIDENCE_INDEX.json`.',
  '',
  `- Complete: ${complete}/${total} = ${percent}%`,
  `- Open: ${open}/${total}`,
  `- Exceptions: ${exceptions}/${total}`,
  '',
  '| Control | Status | Evidence |',
  '| --- | --- | --- |',
];

for (const control of index.controls) {
  const marker = control.status === 'Complete' ? '✅' : control.status === 'Exception' ? '⚠️' : '❌';
  const label = control.control || control.name || control.controlId;
  lines.push(`| ${control.controlId} ${label} | ${marker} ${control.status} | \`${control.evidencePath}\` |`);
}

lines.push('', '_Do not edit this file manually. Regenerate it with `node scripts/security/generate-p1-progress-dashboard.mjs`._', '');
fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, `${lines.join('\n')}\n`);
console.log(`[p1-progress] wrote ${outputPath}`);
