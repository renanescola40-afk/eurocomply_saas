#!/usr/bin/env node
import { readFileSync } from 'node:fs';

const productionTargets = new Set(['production', 'enterprise']);
const nonProductionTargets = new Set(['local', 'development', 'dev', 'preview', 'test']);
const lifecycleEvent = process.env.npm_lifecycle_event ?? '';
const releaseTarget = process.env.RELEASE_TARGET ?? '';
const isPullRequest = process.env.GITHUB_EVENT_NAME === 'pull_request' || process.env.GITHUB_EVENT_NAME === 'pull_request_target';
const isReleaseLifecycle = lifecycleEvent === 'release:readiness' || lifecycleEvent === 'security:release-go-no-go';
const enforceLiveRls = process.argv.includes('--production')
  || productionTargets.has(releaseTarget)
  || (isReleaseLifecycle && !isPullRequest && !nonProductionTargets.has(releaseTarget));

const evidencePath = 'docs/security/evidence/runtime/supabase-live-rls-validation.json';
const registerPath = 'docs/security/P0_RUNTIME_EVIDENCE_REGISTER.md';
const requiredTables = [
  'organizations',
  'organization_members',
  'documents',
  'audit_events',
  'risks',
  'vendors',
  'tasks',
  'subscriptions',
  'notifications',
];
const requiredOperations = [
  'cross_tenant_read',
  'cross_tenant_insert',
  'cross_tenant_update',
  'cross_tenant_delete',
  'same_tenant_read',
];

const requiredFiles = {
  'docs/RELEASE_GO_NO_GO_CHECKLIST.md': [
    'Release Go/No-Go Checklist',
    'Go',
    'Conditional Go',
    'No-Go',
    'Mandatory Go criteria',
    'Automatic No-Go criteria',
    'Evidence mapping',
    'Enterprise rule',
    'docs/RELEASE_APPROVAL_RECORD.md',
    'docs/RELEASE_EVIDENCE_CHECKLIST.md',
    'Supabase RLS live validation evidence is attached',
  ],
  'docs/RELEASE_CANDIDATE_VALIDATION.md': [
    'docs/RELEASE_GO_NO_GO_CHECKLIST.md',
    'Go/No-Go checklist',
    'Go or explicitly approved Conditional Go',
  ],
  'docs/RELEASE_APPROVAL_LINKAGE.md': [
    'RELEASE_APPROVAL_RECORD.md',
    'RELEASE_EVIDENCE_CHECKLIST.md',
    'RELEASE_CANDIDATE_VALIDATION.md',
  ],
};

const failures = [];

function readText(file) {
  try {
    return readFileSync(file, 'utf8');
  } catch {
    failures.push(`${file} is missing`);
    return null;
  }
}

function readJson(file) {
  const content = readText(file);
  if (!content) return null;

  try {
    return JSON.parse(content);
  } catch (error) {
    failures.push(`${file} is invalid JSON: ${error instanceof Error ? error.message : error}`);
    return null;
  }
}

function checkRequiredDocs() {
  for (const [file, tokens] of Object.entries(requiredFiles)) {
    const content = readText(file);
    if (!content) continue;

    for (const token of tokens) {
      if (!content.includes(token)) failures.push(`${file} is missing required token: ${token}`);
    }
  }
}

function registerMarksSupabaseComplete() {
  const register = readText(registerPath);
  if (!register) return false;

  const row = register
    .split('\n')
    .find((line) => line.startsWith('| Supabase live RLS validation completed |'));

  if (!row) {
    failures.push(`${registerPath} missing Supabase live RLS row`);
    return false;
  }

  return row.includes('| Complete |');
}

function checkGithubActionsProvenance(evidence) {
  const provenance = evidence.githubActions;
  if (!provenance || typeof provenance !== 'object' || Array.isArray(provenance)) {
    failures.push(`${evidencePath} missing githubActions provenance`);
    return;
  }

  if (provenance.generatedInGitHubActions !== true) failures.push(`${evidencePath} must be stamped from GitHub Actions`);

  for (const field of ['workflow', 'runId', 'runUrl', 'repository', 'commitSha', 'refName', 'actor', 'eventName', 'stampedAt']) {
    if (!provenance[field] || typeof provenance[field] !== 'string') failures.push(`${evidencePath} githubActions.${field} is missing`);
  }

  const runUrl = typeof provenance.runUrl === 'string' ? provenance.runUrl : '';
  const expectedRunUrlPattern = /^https:\/\/github\.com\/[^/]+\/[^/]+\/actions\/runs\/\d+$/;
  if (!expectedRunUrlPattern.test(runUrl)) {
    failures.push(`${evidencePath} githubActions.runUrl must point to a numeric GitHub Actions run URL`);
  }
}

function enforceSupabaseLiveRlsComplete() {
  const evidence = readJson(evidencePath);
  const registerComplete = registerMarksSupabaseComplete();

  if (!evidence) {
    failures.push(`${evidencePath} must exist for public production`);
    return;
  }

  if (evidence.status !== 'Complete') failures.push(`${evidencePath} status must be Complete for public production`);
  if (evidence.outcome !== 'passed') failures.push(`${evidencePath} outcome must be passed for public production`);
  if (evidence.runner !== 'scripts/security/run-supabase-live-tenant-isolation.mjs') {
    failures.push(`${evidencePath} must be generated by the strict tenant isolation validator`);
  }
  if (!String(evidence.productionGate ?? '').toLowerCase().includes('production')) {
    failures.push(`${evidencePath} must include a production gate statement`);
  }
  checkGithubActionsProvenance(evidence);

  const testCases = Array.isArray(evidence.testCases) ? evidence.testCases : [];
  const failedTests = testCases.filter((test) => test?.passed !== true);
  if (failedTests.length > 0) failures.push(`${evidencePath} contains failing test cases`);

  const tables = new Set(testCases.map((test) => test?.table).filter(Boolean));
  const operations = new Set(testCases.map((test) => test?.operation).filter(Boolean));
  for (const table of requiredTables) {
    if (!tables.has(table)) failures.push(`${evidencePath} missing required table coverage: ${table}`);
  }
  for (const operation of requiredOperations) {
    if (!operations.has(operation)) failures.push(`${evidencePath} missing required operation coverage: ${operation}`);
  }

  if (!registerComplete) failures.push(`${registerPath} must mark Supabase live RLS validation as Complete for public production`);
}

checkRequiredDocs();
if (enforceLiveRls) enforceSupabaseLiveRlsComplete();

if (failures.length > 0) {
  console.error('Release Go/No-Go check failed:');
  for (const failure of failures) console.error(`- ${failure}`);
  process.exit(1);
}

console.log('Release Go/No-Go check passed.');
