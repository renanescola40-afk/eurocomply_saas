#!/usr/bin/env node
import { readFileSync } from 'node:fs';

const productionTargets = new Set(['production', 'enterprise']);
const nonProductionTargets = new Set(['local', 'development', 'dev', 'preview', 'test']);
const lifecycleEvent = process.env.npm_lifecycle_event ?? '';
const releaseTarget = process.env.RELEASE_TARGET ?? '';
const isPullRequest = process.env.GITHUB_EVENT_NAME === 'pull_request' || process.env.GITHUB_EVENT_NAME === 'pull_request_target';
const isReleaseLifecycle = lifecycleEvent === 'release:readiness' || lifecycleEvent === 'security:release-go-no-go';
const enforceLiveRls = process.argv.includes('--production')
  || productionTargets.has(releaseTarget)
  || (isReleaseLifecycle && !isPullRequest && !nonProductionTargets.has(releaseTarget));

const requiredFiles = {
  'docs/RELEASE_GO_NO_GO_CHECKLIST.md': [
    'Release Go/No-Go Checklist',
    'Go',
    'Conditional Go',
    'No-Go',
    'Mandatory Go criteria',
    'Automatic No-Go criteria',
    'Evidence mapping',
    'Enterprise rule',
    'docs/RELEASE_APPROVAL_RECORD.md',
    'docs/RELEASE_EVIDENCE_CHECKLIST.md',
    'Supabase RLS live validation evidence is attached',
  ],
  'docs/RELEASE_CANDIDATE_VALIDATION.md': [
    'docs/RELEASE_GO_NO_GO_CHECKLIST.md',
    'Go/No-Go checklist',
    'Go or explicitly approved Conditional Go',
  ],
  'docs/RELEASE_APPROVAL_LINKAGE.md': [
    'RELEASE_APPROVAL_RECORD.md',
    'RELEASE_EVIDENCE_CHECKLIST.md',
    'RELEASE_CANDIDATE_VALIDATION.md',
  ],
};

const rlsEvidencePath = 'docs/security/evidence/runtime/supabase-live-rls-validation.json';
const rlsRegisterPath = 'docs/security/P0_RUNTIME_EVIDENCE_REGISTER.md';
const strictRlsRunner = 'scripts/security/run-supabase-live-tenant-isolation.mjs';
const requiredTables = [
  'organizations',
  'organization_members',
  'documents',
  'audit_events',
  'risks',
  'vendors',
  'compliance_tasks',
  'subscriptions',
  'notifications',
];
const requiredOperations = [
  'cross_tenant_read',
  'cross_tenant_insert',
  'cross_tenant_update',
  'cross_tenant_delete',
  'same_tenant_read',
];

const failures = [];

function readText(file) {
  try {
    return readFileSync(file, 'utf8');
  } catch {
    failures.push(`${file} is missing`);
    return null;
  }
}

function readJson(file) {
  const source = readText(file);
  if (!source) return null;
  try {
    return JSON.parse(source);
  } catch (error) {
    failures.push(`${file} is not valid JSON: ${error instanceof Error ? error.message : error}`);
    return null;
  }
}

function checkRequiredDocs() {
  for (const [file, tokens] of Object.entries(requiredFiles)) {
    const content = readText(file);
    if (!content) continue;

    for (const token of tokens) {
      if (!content.includes(token)) failures.push(`${file} is missing required token: ${token}`);
    }
  }
}

function checkSupabaseLiveRlsComplete() {
  const evidence = readJson(rlsEvidencePath);
  const register = readText(rlsRegisterPath);
  if (!evidence || !register) return;

  const registerRow = register
    .split('\n')
    .find((line) => line.startsWith('| Supabase live RLS validation completed |'));

  if (!registerRow?.includes('| Complete |')) {
    failures.push(`${rlsRegisterPath} must mark Supabase live RLS validation as Complete for production or enterprise release`);
  }

  if (evidence.status !== 'Complete') failures.push(`${rlsEvidencePath} status must be Complete`);
  if (evidence.outcome !== 'passed') failures.push(`${rlsEvidencePath} outcome must be passed`);
  if (evidence.runner !== strictRlsRunner) failures.push(`${rlsEvidencePath} must be generated by ${strictRlsRunner}`);

  const testCases = Array.isArray(evidence.testCases) ? evidence.testCases : [];
  if (testCases.length === 0) failures.push(`${rlsEvidencePath} must include live test cases`);
  if (testCases.some((test) => test?.passed !== true)) failures.push(`${rlsEvidencePath} contains failing live test cases`);

  const coveredTables = new Set(testCases.map((test) => test?.table).filter(Boolean));
  const coveredOperations = new Set(testCases.map((test) => test?.operation).filter(Boolean));
  for (const table of requiredTables) {
    if (!coveredTables.has(table)) failures.push(`${rlsEvidencePath} missing live table coverage: ${table}`);
  }
  for (const operation of requiredOperations) {
    if (!coveredOperations.has(operation)) failures.push(`${rlsEvidencePath} missing live operation coverage: ${operation}`);
  }
}

checkRequiredDocs();
if (enforceLiveRls) checkSupabaseLiveRlsComplete();

if (failures.length > 0) {
  console.error('Release Go/No-Go check failed:');
  for (const failure of failures) console.error(`- ${failure}`);
  process.exit(1);
}

console.log('Release Go/No-Go check passed.');
